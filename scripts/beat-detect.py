"""
Beat detection helper for syncing Remotion animations to audio.

Usage:
  .earshot-venv/Scripts/python scripts/beat-detect.py public/audio/voiceover.mp3
  .earshot-venv/Scripts/python scripts/beat-detect.py public/audio/voiceover.mp3 --fps 30 --out src/beats.ts

Outputs a TypeScript array of frame numbers where beats occur.
"""
import argparse
import json
import sys

import librosa


def detect_beats(audio_path: str, fps: int = 30) -> dict:
    y, sr = librosa.load(audio_path)
    tempo, beat_frames_audio = librosa.beat.beat_track(y=y, sr=sr)
    beat_times = librosa.frames_to_time(beat_frames_audio, sr=sr)
    beat_frames_video = [round(t * fps) for t in beat_times]
    duration = librosa.get_duration(y=y, sr=sr)

    return {
        "tempo": float(tempo.item()) if hasattr(tempo, 'item') else float(tempo),
        "durationSeconds": round(duration, 2),
        "durationFrames": round(duration * fps),
        "beatFrames": beat_frames_video,
        "beatTimesSeconds": [round(float(t), 3) for t in beat_times],
    }


def to_typescript(data: dict) -> str:
    frames = json.dumps(data["beatFrames"])
    return f"""// Auto-generated by scripts/beat-detect.py
export const BEAT_DATA = {{
  tempo: {data['tempo']:.1f},
  durationSeconds: {data['durationSeconds']},
  durationFrames: {data['durationFrames']},
  beatFrames: {frames},
}} as const;
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Detect beats and output frame numbers")
    parser.add_argument("audio", help="Path to audio file")
    parser.add_argument("--fps", type=int, default=30, help="Video FPS (default: 30)")
    parser.add_argument("--out", help="Output .ts file path (prints to stdout if omitted)")
    args = parser.parse_args()

    data = detect_beats(args.audio, args.fps)
    ts = to_typescript(data)

    if args.out:
        with open(args.out, "w") as f:
            f.write(ts)
        print(f"Wrote {len(data['beatFrames'])} beats to {args.out}")
        print(f"Tempo: {data['tempo']:.1f} BPM | Duration: {data['durationSeconds']}s")
    else:
        print(ts)
